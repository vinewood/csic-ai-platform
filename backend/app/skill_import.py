async def import_all():
    """全量导入技能到数据库"""
    async with async_session() as session:
        # 检查是否已导入
        result = await session.execute(select(Skill).limit(1))
        existing = len(result.scalars().all())
        
        all_skills = SKILLS + QUICK_SKILLS
        imported = 0
        
        for s in all_skills:
            # 检查是否已存在同名技能
            check = await session.execute(select(Skill).where(Skill.name == s["name"]))
            if check.scalar_one_or_none():
                continue
            skill = Skill(
                name=s["name"], category=s["category"], icon=s["icon"],
                prompt=s["prompt"], description=s.get("desc", ""), color=s.get("color", "#1677ff")
            )
            session.add(skill)
            imported += 1
        
        await session.commit()
